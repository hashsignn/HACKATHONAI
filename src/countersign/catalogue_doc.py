"""Render the service catalogue, policy packs and price list as Markdown.

    python -m countersign.catalogue_doc > docs/departments.md

The document is generated from the same configuration the platform enforces, and a
test fails if the committed copy is out of date, so the docs cannot drift from the code.
"""

from __future__ import annotations

from .bootstrap import Settings
from .domain.catalogue import Catalogue
from .domain.models import ComplexityTier, Consequence
from .domain.policy import DEFAULT_SIGNATURE_SLOTS
from .domain.pricing import PriceList

LANES = {
    "ai_led_spot_check": "AI-led, spot-checked",
    "ai_drafts_human_confirms": "AI drafts, person confirms",
    "human_led_blind": "Human-led, blind first pass",
    "ai_drafts_human_edits": "AI drafts, person edits",
    "human_led": "Human-led",
}


def _chf(v: float) -> str:
    return f"{v:,.0f}".replace(",", "'")


def _words(s: str) -> str:
    return s.replace("_", " ")


def render(catalogue: Catalogue, prices: PriceList) -> str:
    out = [
        "# Departments, services and prices",
        "",
        "<!-- Generated by `python -m countersign.catalogue_doc`. Do not edit by hand. -->",
        "",
        f"Price list **{prices.version}**, in {prices.currency}. Every deliverable is priced as "
        "**Judgment** (by complexity tier) plus **Signature** (by consequence). Illustrative numbers.",
        "",
        "| Department | Service | Judgment T1 / T2 / T3 | Signature internal / external / regulatory | Hourly before AI, T2 |",
        "|---|---|---|---|---|",
    ]
    for d in catalogue.departments.values():
        dp = prices.departments[d.key]
        for s in d.services.values():
            sp = dp.services[s.key]
            sig = sp.signature or dp.signature
            j = " / ".join(_chf(sp.judgment[t]) for t in ComplexityTier)
            g = " / ".join(_chf(sig[c]) for c in Consequence)
            out.append(
                f"| {d.name} | {s.name} | {j} | {g} | {_chf(sp.historical_fee[ComplexityTier.TIER2])} |"
            )
    out += [
        "",
        f"Client platform: Judgment times {prices.client_platform_factor:g}. Retainer: {prices.retainer_deliverables} "
        f"deliverables a year at {prices.retainer_discount:.0%} off.",
        "",
    ]
    for d in catalogue.departments.values():
        p = d.policy
        slots = {**DEFAULT_SIGNATURE_SLOTS, **p.signature_slots}
        out += [
            f"## {d.name}",
            "",
            d.summary,
            "",
            f"**Sells:** {', '.join(_words(o.value) for o in p.options)}. "
            f"**Minimum review:** {p.min_review_level.value}."
            + (
                f" **Fees at risk:** up to {p.max_at_risk_share:.0%} of Judgment."
                if p.max_at_risk_share
                else ""
            ),
            "",
            "**Who signs the deliverable:** "
            + "; ".join(
                f"{_words(c.value)}: {' and '.join(_words(s.value) for s in slots[c])}"
                for c in Consequence
            )
            + ".",
            "",
            *[f"- {r}" for r in p.rationale],
            "",
        ]
        for s in d.services.values():
            out += [
                f"### {s.name}",
                "",
                f"{s.deliverable}. Relied on at least as {_words(s.min_consequence.value)}."
                + (" Outcome-linked fees allowed." if s.outcome_linked_allowed else ""),
                "",
                "| | Milestone | Lane | Led by | Share of Judgment |",
                "|---|---|---|---|---|",
                *[
                    f"| {m.key} | {m.title} | {LANES[m.lane.value]} | {_words(m.lead.value)} | {m.weight:.0%} |"
                    for m in s.milestones
                ],
                "",
            ]
            if s.notes:
                out += [s.notes, ""]
    return "\n".join(out)


def main() -> None:
    settings = Settings()
    print(
        render(
            Catalogue.from_dir(settings.catalogue_dir),
            PriceList.from_toml(settings.price_list_path),
        ),
        end="",
    )


if __name__ == "__main__":
    main()
